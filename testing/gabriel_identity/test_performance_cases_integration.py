pytestmark=pytest.mark.integration


@pytest.fixture
def evaluation(tenant,cases):
    return cases.create_case(tenant.token,'Generated performance test',purpose='performance_test')


def test_evaluation_source_cannot_be_proposed_even_with_organization_scope(tenant,cases,evaluation):
    source=cases.acquire(tenant.token,evaluation['id'],uuid4(),'Generated simulator observation','Generated evaluation',approved=True)
    for scope in ('case','organization'):
        with pytest.raises(AccessDenied,match='performance_test_memory_excluded'):
            cases.propose_memory(tenant.token,evaluation['id'],source['id'],uuid4(),'fact',scope,'generated.evaluation')
    assert cases.read_evidence(tenant.token,source['id']).reveal()==b'Generated simulator observation'
    assert cases.list_memory(tenant.token,evaluation['id'])['learning_disabled']
    assert cases.case_report(tenant.token,evaluation['id'])['snapshot']['case']['purpose']=='performance_test'


def test_evaluation_retrieves_no_operational_organization_memory(tenant,cases,case,evidence,evaluation):
    row=cases.propose_memory(tenant.token,case['id'],evidence['id'],uuid4(),'fact','organization','generated.reference')
    cases.review_memory(tenant.token,row['id'],'approved',row['source_digest'],True)
    assert len(cases.retrieve_memory(tenant.token,case['id']))==1
    assert cases.retrieve_memory(tenant.token,evaluation['id'])==[]
    assert cases.list_memory(tenant.token,evaluation['id'])['records']==[]


def test_actual_scheduled_browser_review_preserves_evidence_without_learning(tenant,cases,evaluation,context):
    browser,lease,scope,_,_=enrollment(tenant,cases,evaluation,context,monitoring_approved=True)
    browser.connect_browser(lease.token,scope)
    for sequence in (1,2):
        result=captured_text(browser,tenant,lease,scope,sequence,'Generated simulator\nFailed login for generated-user')
        learning=result['learning']
        assert learning['proposal_state']=='performance_test_excluded' and learning['learning_disabled']
        assert learning['proposal_id'] is None and learning['context_evidence_id'] is None
        assert learning['reviewed_reference_count']==0 and not learning['model_training_performed']
    with owner_connection(tenant.db) as conn:
        assert conn.execute('SELECT count(*) AS n FROM gabriel_identity.memory_records WHERE organization_id=%s',(tenant.org,)).fetchone()['n']==0
        assert conn.execute("SELECT count(*) AS n FROM gabriel_identity.evidence_objects WHERE case_id=%s AND state='ready'",(evaluation['id'],)).fetchone()['n']>=4


def test_database_rejects_purpose_downgrade_and_memory_insert_bypass(tenant,cases,case,evidence,evaluation):
    row=cases.propose_memory(tenant.token,case['id'],evidence['id'],uuid4(),'fact','case','generated.allowed')
    with pytest.raises(psycopg.errors.RaiseException,match='case_purpose_immutable'):
        with owner_connection(tenant.db) as conn:
            conn.execute("UPDATE gabriel_identity.cases SET purpose='investigation' WHERE id=%s",(evaluation['id'],))
    source=cases.acquire(tenant.token,evaluation['id'],uuid4(),'Generated bypass fixture','Generated evaluation',approved=True)
    with pytest.raises(psycopg.errors.RaiseException,match='performance_test_memory_excluded'):
        with owner_connection(tenant.db) as conn:
            conn.execute('''INSERT INTO gabriel_identity.memory_records
                (organization_id,id,case_id,evidence_id,request_id,proposed_by,kind,scope,topic,epoch,source_digest,sensitivity,expires_at)
                SELECT organization_id,%s,%s,%s,%s,proposed_by,kind,scope,topic,epoch,%s,sensitivity,expires_at
                FROM gabriel_identity.memory_records WHERE id=%s''',
                (uuid4(),evaluation['id'],source['id'],uuid4(),source['digest'],row['id']))


def test_upgrade_preserves_existing_case_and_reviewed_memory(tenant,cases,case,evidence):
    row=cases.propose_memory(tenant.token,case['id'],evidence['id'],uuid4(),'fact','case','generated.migration')
    cases.review_memory(tenant.token,row['id'],'approved',row['source_digest'],True)
    with owner_connection(tenant.db) as conn:remove_v31(conn)
    try:migrate(tenant.db.owner)
    finally:migrate(tenant.db.owner)
    assert cases.get_case(tenant.token,case['id'])['case']['purpose']=='investigation'
    assert len(cases.retrieve_memory(tenant.token,case['id']))==1
    for purpose in ('training',None,[]):
        with pytest.raises(InvalidIdentityInput,match='invalid_case_purpose'):
            cases.create_case(tenant.token,'Generated invalid purpose',purpose=purpose)


def test_actual_https_evaluation_form_and_learning_controls(server,tenant,cases):
    cookie,_,_=connect(server)
    status,html,_=call(server,'/cases/new',cookie=cookie)
    assert status==200 and 'Performance test — learning disabled' in html
    nonce=re.search(r'name="nonce" value="([A-Za-z0-9_-]+)"',html)[1]
    status,_,headers=call(server,'/cases',dict(csrf=csrf(html),nonce=nonce,title='Generated HTTPS performance test',purpose='performance_test'),cookie=cookie)
    assert status==303
    path=headers['Location']
    status,html,_=call(server,path,cookie=cookie)
    assert status==200 and 'Performance test: learning disabled' in html
    status,html,_=call(server,path+'/memory',cookie=cookie)
    assert status==200 and 'Learning proposals and reference reuse are disabled' in html
    assert 'Propose reference' not in html and 'Reset all organization memory' not in html
    assert call(server,path+'/memory/reset',dict(csrf=csrf(html),epoch='0'),cookie=cookie)[0]==403
